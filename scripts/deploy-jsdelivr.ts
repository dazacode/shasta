// Shasta Lite on jsDelivr: `bun run deploy:jsdelivr` (from the root, so the root .env is loaded)
//   -> https://cdn.jsdelivr.net/gh/dazacode/shasta-lite/index.svg
// jsDelivr serves the files of a public GitHub repo (`SHASTA_JSDELIVR_REPO`, default dazacode/shasta-lite; created on
// the first run with `gh`). Same Lite build as Base44/Vercel (scripts/lib/liteBuild.ts), with three differences:
//   - it lives in a folder (/gh/<repo>/), so it is built with that Vite base and the engine's prefix under it;
//   - jsDelivr serves .html as text/plain, so the address people open is index.svg: a tiny SVG document that registers
//     the service worker and reloads; from then on the worker answers that address with index.html as a real page,
//     with the isolation headers (public/sw.js, CDN_BASE);
//   - cdn.jsdelivr.net is ONE origin for every npm package and GitHub repo on jsDelivr, so their pages could read its
//     storage: VITE_SHARED_ORIGIN keeps sites' logins and storage in the tab (lib/sharedOrigin.ts + the engine's
//     storageScope), so signing in to a site lasts until the tab closes.
// The VPS must list https://cdn.jsdelivr.net in APP_ORIGINS for the Store and chat. jsDelivr keeps a file for 12 h at
// its edge (a week in browsers): every file without a hash in its name is purged after the push.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { buildLite, FULL, ROOT, run } from "./lib/liteBuild";

const REPO = process.env.SHASTA_JSDELIVR_REPO ?? "dazacode/shasta-lite";
const BASE = `/gh/${REPO}/`;
const CDN = "https://cdn.jsdelivr.net";
const DIR = join(ROOT, ".deploy/jsdelivr");
const BUILD = join(DIR, "build");
const CLONE = join(DIR, "repo");
const dry = process.argv.includes("--dry-run");
// jsDelivr's own limits for GitHub files
const MAX_FILE = 20 * 1024 * 1024;

// Umami website "Shasta Lite (jsDelivr)"
// Ads: none (no Adsterra site for cdn.jsdelivr.net in scripts/lib/adCodes.ts; another host's codes must not run here)
buildLite(BUILD, "32359927-bca9-4b7e-82fe-d41315829b1a", BASE, { VITE_SHARED_ORIGIN: "1" });

// the service worker answers the entry addresses (public/sw.js CDN_BASE)
const swPath = join(BUILD, "sw.js");
const sw = readFileSync(swPath, "utf8");
if (!sw.includes('"__SHASTA_CDN_BASE__"')) fail("sw.js has no __SHASTA_CDN_BASE__ marker");
writeFileSync(swPath, sw.replace('"__SHASTA_CDN_BASE__"', JSON.stringify(BASE)));

// every file Shasta's page names must be inside the folder: a root address would be someone else's (or nothing)
const html = readFileSync(join(BUILD, "index.html"), "utf8");
const rooted = [...html.matchAll(/(?:src|href)="(\/[^"]*)"/g)].map((m) => m[1]).filter((u) => !u.startsWith(BASE));
if (rooted.length) fail(`index.html names files outside ${BASE}: ${rooted.join(", ")}`);

// the web app manifest's addresses are relative to itself
const manifestPath = join(BUILD, "manifest.webmanifest");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
Object.assign(manifest, { id: "./", start_url: "./index.svg", scope: "./" });
for (const icon of manifest.icons ?? []) icon.src = `.${icon.src}`;
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));

writeFileSync(join(BUILD, "index.svg"), bootSvg());
cpSync(join(ROOT, "LICENSE"), join(BUILD, "LICENSE"));
writeFileSync(
	join(BUILD, "README.md"),
	`# Shasta Lite\n\nThe built files of Shasta Lite, served by jsDelivr: ${CDN}${BASE}index.svg\n\n` +
		`Generated by \`bun run deploy:jsdelivr\`; never edit this repository by hand. Shasta is licensed under the ` +
		`GNU AGPL-3.0 (LICENSE). Its source code: https://github.com/dazacode/shasta. The full site: ${FULL}\n`,
);

const files = walk(BUILD);
const big = files.filter((f) => statSync(join(BUILD, f)).size > MAX_FILE);
if (big.length) fail(`jsDelivr serves files up to 20 MB: ${big.join(", ")}`);

if (dry) {
	console.log(`built in ${BUILD} (--dry-run: not pushed)`);
	process.exit(0);
}

// the repo: cloned once, then its tree is replaced by the build on every deploy
if (!existsSync(join(CLONE, ".git"))) {
	const exists = Bun.spawnSync(["gh", "repo", "view", REPO, "--json", "name"], { stdout: "ignore", stderr: "ignore" }).exitCode === 0;
	if (!exists) run(["gh", "repo", "create", REPO, "--public", "--description", "Shasta Lite, served by jsDelivr (generated; source: github.com/dazacode/shasta)"], ROOT);
	rmSync(CLONE, { recursive: true, force: true });
	mkdirSync(CLONE, { recursive: true });
	run(["git", "init", "-q", "-b", "main"], CLONE);
	run(["git", "remote", "add", "origin", `git@github.com:${REPO}.git`], CLONE);
	if (exists) {
		run(["git", "fetch", "-q", "origin"], CLONE);
		if (Bun.spawnSync(["git", "rev-parse", "--verify", "-q", "origin/main"], { cwd: CLONE }).exitCode === 0) run(["git", "reset", "-q", "origin/main"], CLONE);
	}
}
// Keep the chunks of the previous KEEP builds: browsers cache jsDelivr pages for up to a week, and a page from an
// older build asks for its own lazy chunks ("Failed to fetch dynamically imported module" once they were deleted).
// builds.json = each build's own assets/ list, newest first; before it existed, every commit was one pure build.
const KEEP = 3;
const git = (args: string[]) => Bun.spawnSync(["git", ...args], { cwd: CLONE });
const own = files.filter((f) => f.startsWith("assets/"));
const hasHead = git(["rev-parse", "--verify", "-q", "HEAD"]).exitCode === 0;
let history: string[][] = [];
if (existsSync(join(CLONE, "builds.json"))) history = JSON.parse(readFileSync(join(CLONE, "builds.json"), "utf8"));
else if (hasHead)
	for (let i = 0; i < KEEP; i++) {
		const r = git(["ls-tree", "--name-only", `HEAD~${i}`, "assets/"]);
		if (r.exitCode === 0) history.push(r.stdout.toString().split("\n").filter(Boolean));
	}
const ownSet = new Set(own);
const kept = new Map<string, Uint8Array>();
for (const f of new Set(history.slice(0, KEEP).flat())) {
	if (ownSet.has(f)) continue;
	for (let i = 0; i < KEEP && hasHead; i++) {
		const r = git(["show", `HEAD~${i}:${f}`]);
		if (r.exitCode === 0) {
			kept.set(f, r.stdout);
			break;
		}
	}
}

for (const name of readdirSync(CLONE)) if (name !== ".git") rmSync(join(CLONE, name), { recursive: true, force: true });
cpSync(BUILD, CLONE, { recursive: true });
for (const [f, bytes] of kept) writeFileSync(join(CLONE, f), bytes);
writeFileSync(join(CLONE, "builds.json"), JSON.stringify([own, ...history].slice(0, KEEP + 1)));
console.log(`kept ${kept.size} chunks of the previous ${Math.min(KEEP, history.length)} builds`);
run(["git", "add", "-A"], CLONE);
const changed = Bun.spawnSync(["git", "diff", "--cached", "--quiet"], { cwd: CLONE }).exitCode !== 0;
if (changed) {
	const source = Bun.spawnSync(["git", "rev-parse", "--short", "HEAD"], { cwd: ROOT }).stdout.toString().trim();
	run(["git", "commit", "-q", "-m", `Shasta Lite (built from ${source})`], CLONE);
	run(["git", "push", "-q", "origin", "main"], CLONE);
} else console.log("nothing changed since the last deploy");

// jsDelivr's edge keeps files 12 h: purge every file whose name does not change with its contents
const purge = files.filter((f) => !f.startsWith("assets/"));
let failed = 0;
for (const f of purge) {
	const r = await fetch(`https://purge.jsdelivr.net${BASE}${f}`).catch(() => null);
	if (!r?.ok) failed++;
}
console.log(`purged ${purge.length - failed}/${purge.length} files on jsDelivr`);

// jsDelivr picks up the new commit within a few minutes: wait until it serves this build's service worker
const want = readFileSync(swPath, "utf8");
for (let i = 0; ; i++) {
	const got = await fetch(`${CDN}${BASE}sw.js`, { cache: "no-store" }).then((r) => (r.ok ? r.text() : ""), () => "");
	if (got === want) break;
	if (i === 30) {
		console.log("\x1b[33mjsDelivr still serves the previous sw.js after 5 minutes; run the deploy again later to purge once more\x1b[0m");
		break;
	}
	await Bun.sleep(10_000);
	for (const f of ["sw.js", "index.html", "index.svg"]) await fetch(`https://purge.jsdelivr.net${BASE}${f}`).catch(() => null);
}
console.log(`\nShasta Lite on jsDelivr: ${CDN}${BASE}index.svg`);
console.log("\x1b[33mpublic source must match what is hosted: run `bun run publish:source` (AGPL section 13)\x1b[0m");

function walk(dir: string): string[] {
	return readdirSync(dir).flatMap((name) => {
		const p = join(dir, name);
		return statSync(p).isDirectory() ? walk(p) : [relative(BUILD, p)];
	});
}

function fail(message: string): never {
	console.error(message);
	process.exit(1);
}

/** The address people open: registers the service worker, then reloads into the real page it serves. */
function bootSvg() {
	return `<svg xmlns="http://www.w3.org/2000/svg" width="100%" height="100%">
<title>Shasta</title>
<style>svg{background:#13151b;font-family:system-ui,-apple-system,"Segoe UI",sans-serif}text{fill:#e7e9ee;text-anchor:middle}.s{fill:#9aa3b2;font-size:14px}</style>
<rect width="100%" height="100%" fill="#13151b"/>
<text x="50%" y="46%" font-size="28" font-weight="600">Shasta</text>
<text id="msg" class="s" x="50%" y="53%">Starting…</text>
<script><![CDATA[
(function () {
  var msg = document.getElementById("msg");
  function say(t) { msg.textContent = t; }
  var base = location.pathname.replace(/[^/]*$/, "");
  var tries = 0;
  try { tries = +sessionStorage.getItem("shasta-boot") || 0; sessionStorage.setItem("shasta-boot", String(tries + 1)); } catch (e) {}
  if (tries > 2) { say("Shasta could not start here. Reload the page to try again."); try { sessionStorage.removeItem("shasta-boot"); } catch (e) {} return; }
  if (!("serviceWorker" in navigator)) { say("This browser cannot run Shasta (no service workers)."); return; }
  function go() { location.reload(); }
  navigator.serviceWorker.addEventListener("controllerchange", go);
  navigator.serviceWorker.register(base + "sw.js", { scope: base, updateViaCache: "none" }).then(function () {
    if (navigator.serviceWorker.controller) return go();
    // the engine's worker claims open pages as soon as it is active
    return navigator.serviceWorker.ready.then(function () { setTimeout(go, 1500); });
  }).catch(function (e) { say("Shasta could not start: " + (e && e.message || e)); });
})();
]]></script>
</svg>
`;
}
