import { chromium } from '@playwright/test'
const base = process.env.BASE
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } })
const page = await ctx.newPage()
await page.goto(base, { waitUntil: 'domcontentloaded' })
await page.getByRole('button', { name: 'Watch', exact: true }).first().click()
await page.getByRole('heading', { name: 'Watch' }).waitFor({ timeout: 30000 })
await page.getByRole('searchbox').fill('fight club')
await page.waitForTimeout(4000)
await page.locator('button[data-card]').first().click()
await page.waitForTimeout(18000)
const vol = await page.getByRole('button', { name: /^(Mute|Unmute)$/ }).count()
const slider = await page.locator('input[aria-label="Volume"]').count()
const zap = await page.getByRole('button', { name: /Switch to (direct|proxied) playback/ }).count()
const srcBtn = await page.getByRole('button', { name: 'Source' }).count()
const fs = await page.getByRole('button', { name: 'Full screen' }).count()
const paused = await page.evaluate(() => { const f = document.querySelector('iframe'); try { return !!f.contentDocument.querySelector('video')?.paused } catch { return 'no-access' } })
await page.screenshot({ path: '/tmp/live-final.png' })
console.log(`${base} -> volume=${vol} slider=${slider} zap=${zap} source=${srcBtn} fullscreen=${fs} embedVideoPaused=${paused}`)
await b.close()
